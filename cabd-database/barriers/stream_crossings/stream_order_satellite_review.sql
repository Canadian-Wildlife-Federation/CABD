-- ============================================================================
-- Backfill stream_order in stream_crossings.cwf_satellite_review
-- from CHyF Strahler order, via FDW.
--
-- Author: Katherine O'Hearn
-- Last updated: 2026-09-18
--
-- WHAT THIS DOES
--   For each modelled crossing in the listed work units that has no
--   stream_order in the satellite review table, find the NEAREST CHyF
--   flowpath segment within 0.0001 degrees (~11 m) and, if that segment's
--   Strahler order is greater than 1, write it to the review table.
--
-- MATCHING RULES (deliberate - do not change without reading the notes)
--   1. Tolerance is 0.0001 degrees (~11 m in EPSG 4617), NOT 0.001 (~100 m).
--      Modelled crossings are generated by intersecting road/rail against the
--      stream network, so they sit essentially on a flowpath. A wide tolerance
--      only pulls in confluence neighbours.
--
--   2. Match is NEAREST SEGMENT, not MAX(strahler_order) within tolerance.
--      Near a confluence a crossing can be within tolerance of both a small
--      tributary and the larger stream it joins. Taking the max silently
--      promotes headwater crossings to the order of the neighbouring stream.
--
--   3. The "> 1" test is applied to the CHOSEN match, NOT as a filter on
--      candidate segments. This is the important one. If you filter the cache
--      to strahler_order > 1 first, an order-1 crossing near a confluence
--      loses its correct match and silently inherits the higher order instead.
--      Order-1 crossings are meant to stay NULL.
--
-- PREREQUISITES
--   - public.eflowpath_properties_vw exists as a foreign table into chyf2
--     and exposes: id, aoi_id, strahler_order, geometry
--   - If CHyF geometry gains/loses dimensions, the foreign table column may
--     need relaxing:
--         ALTER FOREIGN TABLE public.eflowpath_properties_vw
--             ALTER COLUMN geometry TYPE geometry;
--     Symptom is: "Geometry has Z dimension but column does not"
--
-- HOW TO RUN
--   Run every step in the SAME session - the temp tables do not survive
--   a reconnect. Edit the work unit list in STEP 1 and nowhere else.
--
-- CAUTION
--   Do not create permanent tables named tmp_*. A permanent public.tmp_chyf_streams
--   will shadow or be shadowed by the temp table depending on search_path,
--   and you will silently query the wrong one. STEP 4 checks for this.
-- ============================================================================


